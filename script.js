let preferenceStorageWarningShown = false;

function handlePreferenceStorageError(error) {
  if (error instanceof DOMException && error.name === 'SecurityError') {
    if (!preferenceStorageWarningShown) {
      console.warn('Browser storage is unavailable; preferences will not persist.', error);
      preferenceStorageWarningShown = true;
    }
    return;
  }
  throw error;
}

function getStoredPreference(key) {
  try {
    return localStorage.getItem(key);
  } catch (error) {
    handlePreferenceStorageError(error);
    return null;
  }
}

function savePreference(key, value) {
  try {
    localStorage.setItem(key, value);
  } catch (error) {
    handlePreferenceStorageError(error);
  }
}

function applyLanguage(language) {
  const entries = document.querySelectorAll('[data-i18n]');
  const dictionary = translations[language] || translations.ar;

  entries.forEach((element) => {
    const key = element.dataset.i18n;
    if (Object.prototype.hasOwnProperty.call(dictionary, key)) {
      element.textContent = dictionary[key];
    }
  });

  document.querySelectorAll('[data-i18n-aria-label]').forEach((element) => {
    const key = element.dataset.i18nAriaLabel;
    if (Object.prototype.hasOwnProperty.call(dictionary, key)) {
      element.setAttribute('aria-label', dictionary[key]);
    }
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
    const key = element.dataset.i18nPlaceholder;
    if (Object.prototype.hasOwnProperty.call(dictionary, key)) {
      element.setAttribute('placeholder', dictionary[key]);
    }
  });
  document.querySelectorAll('[data-i18n-alt]').forEach((element) => {
    const key = element.dataset.i18nAlt;
    if (Object.prototype.hasOwnProperty.call(dictionary, key)) {
      element.setAttribute('alt', dictionary[key]);
    }
  });

  root.lang = language;
  root.dir = language === 'ar' ? 'rtl' : 'ltr';
  document.title = dictionary['meta.title'];
  document.querySelector('meta[name="description"]').content = dictionary['meta.description'];
  savePreference(langStorageKey, language);
  langToggle.textContent = language === 'ar' ? 'EN' : 'عربي';
  langToggle.setAttribute('aria-label', language === 'ar' ? 'التبديل إلى الإنجليزية' : 'Switch to Arabic');
  navToggle.setAttribute('aria-label', navToggle.getAttribute('aria-expanded') === 'true'
    ? dictionary['nav.closeMenu']
    : dictionary['nav.openMenu']);

  const themeLabel = root.getAttribute('data-theme') === 'dark'
    ? (language === 'ar' ? 'التبديل إلى الوضع الفاتح' : 'Switch to Light Mode')
    : (language === 'ar' ? 'التبديل إلى الوضع الداكن' : 'Switch to Dark Mode');
  themeToggle.setAttribute('aria-label', themeLabel);
  themeToggle.querySelector('.sr-only').textContent = themeLabel;
}

function applyTheme(theme) {
  root.setAttribute('data-theme', theme);
  savePreference(themeStorageKey, theme);

  const isDark = theme === 'dark';
  themeToggle.querySelector('.theme-icon').textContent = isDark ? '☀' : '☾';
  const themeLabel = root.lang === 'ar'
    ? (isDark ? 'التبديل إلى الوضع الفاتح' : 'التبديل إلى الوضع الداكن')
    : (isDark ? 'Switch to Light Mode' : 'Switch to Dark Mode');
  themeToggle.setAttribute('aria-label', themeLabel);
  themeToggle.querySelector('.sr-only').textContent = themeLabel;
}

function setInitialPreferences() {
  const savedTheme = getStoredPreference(themeStorageKey);
  const savedLang = getStoredPreference(langStorageKey);
  const prefersDark = window.matchMedia('(prefers-color-scheme: dark)').matches;
  const initialTheme = savedTheme || (prefersDark ? 'dark' : 'light');
  const initialLang = savedLang || 'ar';

  applyTheme(initialTheme);
  applyLanguage(initialLang);
}

function initializeScrollReveals() {
  if (
    window.matchMedia('(prefers-reduced-motion: reduce)').matches
    || !('IntersectionObserver' in window)
  ) {
    return;
  }

  const revealTargets = document.querySelectorAll(
    '.hero-content, .hero-visual, .section-heading, .info-card, .stats-panel, .skill-card, .project-card, .timeline-item, .contact-card, .contact-form'
  );
  const observer = new IntersectionObserver((entries, currentObserver) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add('is-visible');
        currentObserver.unobserve(entry.target);
      }
    });
  }, {
    threshold: 0.12,
    rootMargin: '0px 0px -32px 0px'
  });

  revealTargets.forEach((element) => {
    element.classList.add('reveal-item');
    observer.observe(element);
  });
  root.classList.add('motion-enabled');
}

function setActiveNavigation(sectionId) {
  document.querySelectorAll('.nav-links a').forEach((link) => {
    const isActive = link.hash === `#${sectionId}`;
    link.classList.toggle('active', isActive);
    if (isActive) {
      link.setAttribute('aria-current', 'location');
    } else {
      link.removeAttribute('aria-current');
    }
  });
}

function initializeActiveNavigation() {
  const navLinks = Array.from(document.querySelectorAll('.nav-links a[href^="#"]'));
  const sections = navLinks
    .map((link) => document.getElementById(link.hash.slice(1)))
    .filter(Boolean);

  const initialSectionId = sections.some((section) => `#${section.id}` === window.location.hash)
    ? window.location.hash.slice(1)
    : sections[0]?.id;

  if (initialSectionId) {
    setActiveNavigation(initialSectionId);
  }
  if (!('IntersectionObserver' in window)) {
    return;
  }

  const intersectingSections = new Set();
  const header = document.querySelector('.site-header');
  const headerOffset = Math.ceil(header.getBoundingClientRect().height);
  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        intersectingSections.add(entry.target);
      } else {
        intersectingSections.delete(entry.target);
      }
    });

    const rootBounds = entries.find((entry) => entry.rootBounds)?.rootBounds;
    const activationLine = rootBounds
      ? rootBounds.top + rootBounds.height / 2
      : window.innerHeight * 0.25;
    const visibleSections = sections
      .filter((section) => intersectingSections.has(section))
      .map((section) => ({ section, bounds: section.getBoundingClientRect() }));
    const currentSection = visibleSections
      .filter(({ bounds }) => bounds.top <= activationLine && bounds.bottom > activationLine)
      .sort((a, b) => b.bounds.top - a.bounds.top)[0]
      || visibleSections.sort((a, b) => (
        Math.abs(a.bounds.top - activationLine) - Math.abs(b.bounds.top - activationLine)
      ))[0];

    if (currentSection) {
      setActiveNavigation(currentSection.section.id);
    }
  }, {
    threshold: 0,
    rootMargin: `-${headerOffset}px 0px -65% 0px`
  });

  sections.forEach((section) => observer.observe(section));
}

langToggle.addEventListener('click', () => {
  const nextLanguage = root.lang === 'ar' ? 'en' : 'ar';
  applyLanguage(nextLanguage);
});

themeToggle.addEventListener('click', () => {
  const nextTheme = root.getAttribute('data-theme') === 'dark' ? 'light' : 'dark';
  applyTheme(nextTheme);
});

navToggle.addEventListener('click', () => {
  const isExpanded = navToggle.getAttribute('aria-expanded') === 'true';
  navToggle.setAttribute('aria-expanded', String(!isExpanded));
  navToggle.setAttribute('aria-label', translations[root.lang][isExpanded ? 'nav.openMenu' : 'nav.closeMenu']);
  navPanel.classList.toggle('is-open');
});

document.querySelectorAll('.nav-links a').forEach((link) => {
  link.addEventListener('click', () => {
    setActiveNavigation(link.hash.slice(1));
    navPanel.classList.remove('is-open');
    navToggle.setAttribute('aria-expanded', 'false');
    navToggle.setAttribute('aria-label', translations[root.lang]['nav.openMenu']);
  });
});

document.querySelector('.contact-form').addEventListener('submit', (event) => {
  event.preventDefault();
  const form = event.currentTarget;
  const name = form.querySelector('input[name="name"]').value.trim();
  const emailInput = form.querySelector('input[name="email"]');
  const email = emailInput.value.trim();
  const message = form.querySelector('textarea[name="message"]').value.trim();

  if (!name || !email || !message || !emailInput.validity.valid) {
    statusText.dataset.i18n = 'form.error';
    statusText.textContent = translations[root.lang]['form.error'];
    statusText.classList.add('error');
    return;
  }

  statusText.dataset.i18n = 'form.config';
  statusText.textContent = translations[root.lang]['form.config'];
  statusText.classList.remove('error');
  form.reset();
});

